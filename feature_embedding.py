import torch.nn as nn
from torch_geometric.nn import GCNConv, SAGEConv, GATConv, GINConv, APPNP, TransformerConv
import torch.nn.functional as F



class GCNEncoder(nn.Module):
    """
    GCN (Graph Convolutional Network) encoder that generates node embeddings from input features and graph structure.

    Inputs:
    - x (torch.Tensor): node feature matrix of shape [num_nodes, in_features].
    - edge_index (torch.Tensor): adjacency matrix in PyTorch Geometric format, of shape [2, num_edges].

    Outputs:
    - h (torch.Tensor): node embeddings produced by the GCN, of shape [num_nodes, out_dim].
    """

    def __init__(self, in_features, hidden_dim, out_dim):
        super(GCNEncoder, self).__init__()
        # Two-layer GCN: conv1 transforms input features to hidden_dim, conv2 to out_dim
        self.conv1 = GCNConv(in_features, hidden_dim)
        self.conv2 = GCNConv(hidden_dim, out_dim)
        # Dropout layer for regularization
        self.dropout = nn.Dropout(p=0.5)
        
    def forward(self, x, edge_index):
        # First GCN layer
        h = self.conv1(x, edge_index)
        h = F.relu(h)
        h = self.dropout(h)
        # Second GCN layer
        h = self.conv2(h, edge_index)
        # (Optional) You could apply non-linearity here if desired:
        # h = F.relu(h)
        return h  # shape [num_nodes, out_dim]




class SAGEEncoder(nn.Module):
    """
    GraphSAGE (Sample and Aggregate) encoder that produces node embeddings from input features and the local graph structure.

    Inputs:
    - x (torch.Tensor): node feature matrix of shape [num_nodes, in_features].
    - edge_index (torch.Tensor): graph edge indices of shape [2, num_edges], in PyTorch Geometric format.

    Outputs:
    - h (torch.Tensor): generated node embeddings of shape [num_nodes, out_dim].
    """

    def __init__(self, in_features, hidden_dim, out_dim):
        super(SAGEEncoder, self).__init__()
        self.conv1 = SAGEConv(in_features, hidden_dim)
        self.conv2 = SAGEConv(hidden_dim, out_dim)
        self.dropout = nn.Dropout(p=0.5)

    def forward(self, x, edge_index):
        h = self.conv1(x, edge_index)
        h = F.relu(h)
        h = self.dropout(h)
        h = self.conv2(h, edge_index)
        return h




class GATEncoder(nn.Module):
    """
    GAT (Graph Attention Network) encoder that uses attention mechanisms to aggregate information from neighboring nodes.

    Inputs:
    - x (torch.Tensor): node feature matrix of shape [num_nodes, in_features].
    - edge_index (torch.Tensor): graph edge indices of shape [2, num_edges], in PyTorch Geometric format.

    Outputs:
    - h (torch.Tensor): node embeddings produced by the GAT, of shape [num_nodes, out_dim].
    """

    def __init__(self, in_features, hidden_dim, out_dim, heads=4):
        super(GATEncoder, self).__init__()
        self.gat1 = GATConv(in_features, hidden_dim, heads=heads)
        self.gat2 = GATConv(hidden_dim * heads, out_dim, heads=1)
        self.dropout = nn.Dropout(0.5)

    def forward(self, x, edge_index):
        h = self.gat1(x, edge_index)
        h = F.elu(h)
        h = self.dropout(h)
        h = self.gat2(h, edge_index)
        return h




class GINEncoder(nn.Module):
    """
    GIN (Graph Isomorphism Network) encoder designed to capture the topological structure of the graph with high discriminative power.

    Inputs:
    - x (torch.Tensor): node feature matrix of shape [num_nodes, in_features].
    - edge_index (torch.Tensor): graph edge indices of shape [2, num_edges], in PyTorch Geometric format.

    Outputs:
    - h (torch.Tensor): node embeddings generated by the GIN, of shape [num_nodes, out_dim].
    """

    def __init__(self, in_features, hidden_dim, out_dim):
        super().__init__()
        nn1 = nn.Sequential(nn.Linear(in_features, hidden_dim), nn.ReLU(), nn.Linear(hidden_dim, hidden_dim))
        self.conv1 = GINConv(nn1)
        nn2 = nn.Sequential(nn.Linear(hidden_dim, out_dim), nn.ReLU(), nn.Linear(out_dim, out_dim))
        self.conv2 = GINConv(nn2)
        self.dropout = nn.Dropout(0.5)

    def forward(self, x, edge_index):
        h = self.conv1(x, edge_index)
        h = F.relu(h)
        h = self.dropout(h)
        h = self.conv2(h, edge_index)
        return h
    
    
    
    
    
    
class APPNPEncoder(nn.Module):
    """
    APPNP (Approximate Personalized Propagation of Neural Predictions) encoder that combines MLP layers with personalized propagation over the graph.

    Inputs:
    - x (torch.Tensor): node feature matrix of shape [num_nodes, in_features].
    - edge_index (torch.Tensor): graph edge indices of shape [2, num_edges], in PyTorch Geometric format.

    Outputs:
    - x (torch.Tensor): node embeddings after propagation, of shape [num_nodes, out_dim].
    """

    def __init__(self, in_features, hidden_dim, out_dim, K=10, alpha=0.1):
        super().__init__()
        self.lin1 = nn.Linear(in_features, hidden_dim)
        self.lin2 = nn.Linear(hidden_dim, out_dim)
        self.prop = APPNP(K=K, alpha=alpha)
        self.dropout = nn.Dropout(0.5)

    def forward(self, x, edge_index):
        x = self.lin1(x)
        x = F.relu(x)
        x = self.dropout(x)
        x = self.lin2(x)
        x = self.prop(x, edge_index)
        return x




class TransformerGNNEncoder(nn.Module):
    """
    Transformer-based GNN encoder that applies multi-head attention to aggregate information from neighboring nodes.

    Inputs:
    - x (torch.Tensor): node feature matrix of shape [num_nodes, in_features].
    - edge_index (torch.Tensor): graph edge indices of shape [2, num_edges], in PyTorch Geometric format.

    Outputs:
    - h (torch.Tensor): node embeddings produced by the TransformerConv layers, of shape [num_nodes, out_dim].
    """

    def __init__(self, in_features, hidden_dim, out_dim):
        super().__init__()
        self.conv1 = TransformerConv(in_features, hidden_dim, heads=2)
        self.conv2 = TransformerConv(hidden_dim * 2, out_dim, heads=1)
        self.dropout = nn.Dropout(0.5)

    def forward(self, x, edge_index):
        h = self.conv1(x, edge_index)
        h = F.relu(h)
        h = self.dropout(h)
        h = self.conv2(h, edge_index)
        return h
    
    
    
    
    
    
    
def select_embed_model(NAME):
    """
    Returns the GNN encoder class corresponding to the specified model name.

    Inputs:
    - NAME (str): name of the desired encoder model. Must be one of:
                  'GCN', 'SAGE', 'GAT', 'GIN', 'APPNP', 'TransformerGNN'.

    Outputs:
    - (class): the corresponding encoder class (not instantiated).

    Raises:
    - ValueError: if the model name is not recognized.
    """

    if NAME=='GCN':
        return GCNEncoder
    elif NAME=='SAGE':
        return SAGEEncoder
    elif NAME=='GAT':
        return GATEncoder
    elif NAME=='GIN':
        return GINEncoder
    elif NAME=='APPNP':
        return APPNPEncoder
    elif NAME=='TransformerGNN':
        return TransformerGNNEncoder
    else:
        raise ValueError(f"Embedding model {NAME} is invalid.")